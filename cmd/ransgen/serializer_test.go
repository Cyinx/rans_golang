// fixtureDir 序列化器 fixture：testdata 下的真实包（input.go 手写 +
// rans_gen.go 生成入库）。./... 跳过 testdata，行为测试由
// TestFixturePackageGreen 以显式路径驱动。
var fixtureDir = filepath.Join("testdata", "serial_demo")

// gateSrc 构造门卫 fixture：Point 为合法被引用消息，M.F 为被测字段类型。
func gateSrc(typ string) string {
	return "package x\n\ntype Point struct {\n\tX int64 " + orderTag(1) + "\n}\n\ntype M struct {\n\tF " + typ + " " + orderTag(1) + "\n}\n"
}

// TestPlanUnsupportedFieldTypes S004/M405 门卫：支持集外类型一律生成失败，
// 错误文本含字段名与类型名。
func TestPlanUnsupportedFieldTypes(t *testing.T) {
	for _, typ := range []string{
		"chan int",
		"map[string]int",
		"func(int) error",
		"any",
		"interface{}",
		"*Point",    // 指针（即便指向已声明消息）
		"time.Time", // 限定名（未声明）
		"Missing",   // 未声明本包 struct
		"int32",     // 支持集外的定宽整数
		"[]int32",
		"[]*Point",
		"[][]int",
		"[]any",
	} {
		t.Run(typ, func(t *testing.T) {
			dir := writePkg(t, map[string]string{"x.go": gateSrc(typ)})
			pkg, err := LoadPackage(dir, "")
			if err != nil {
				t.Fatalf("LoadPackage: %v", err)
			}
			_, err = planGen(pkg)
			if err == nil {
				t.Fatalf("类型 %s 未被门卫拦截", typ)
			}
			for _, want := range []string{"F", typ, "S004/M405"} {
				if !strings.Contains(err.Error(), want) {
					t.Fatalf("err = %v, want 含 %q", err, want)
				}
			}
		})
	}
}

// renderPlan 走全渲染管线（planGen + 模板），供确定性断言复用。
func renderPlan(t *testing.T, pkg *PackageDecl) []byte {
	t.Helper()
	model, err := planGen(pkg)
	if err != nil {
		t.Fatalf("planGen: %v", err)
	}
	out, err := Render(model, ransgenTemplate)
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	return out
}

// TestSerializerRenderIdempotentAndFresh 幂等锁（两次全流程字节相等） +
// 漂移锁（入库 rans_gen.go 与再生成一致——生成器改动未重新生成即红）。
func TestSerializerRenderIdempotentAndFresh(t *testing.T) {
	pkg, err := LoadPackage(fixtureDir, "rans_gen.go")
	if err != nil {
		t.Fatalf("LoadPackage: %v", err)
	}
	first := renderPlan(t, pkg)

	pkg2, err := LoadPackage(fixtureDir, "rans_gen.go")
	if err != nil {
		t.Fatalf("LoadPackage twice: %v", err)
	}
	second := renderPlan(t, pkg2)

	if !bytes.Equal(first, second) {
		t.Fatalf("两次生成不一致:\n%q\n%q", first, second)
	}
	for _, want := range []string{
		"// Code generated by ransgen. DO NOT EDIT.",
		`codec.Register("serial.Shape"`,
		"r.SkipField(wt)",
		"var RansShapes = []string{",
		`"Shape:Label:1:string"`,
	} {
		if !bytes.Contains(first, []byte(want)) {
			t.Fatalf("生成物缺 %q:\n%s", want, first)
		}
	}

	committed, err := os.ReadFile(filepath.Join(fixtureDir, "rans_gen.go"))
	if err != nil {
		t.Fatalf("读入库生成物: %v", err)
	}
	if !bytes.Equal(first, committed) {
		t.Fatalf("入库 rans_gen.go 与再生成不一致（需重新生成并入库）")
	}
}

// TestSerializerRenderNormalizesInput 乱序输入（消息/字段乱声明）与正序
// 输入渲染字节一致；planGen 就地归一。
func TestSerializerRenderNormalizesInput(t *testing.T) {
	shuffled := &PackageDecl{
		Name: "x",
		Messages: []MessageDecl{
			{Name: "m2", TypeName: "M2", Fields: []FieldDecl{{Name: "b", Type: "string", Order: 2}, {Name: "a", Type: "string", Order: 1}}},
			{Name: "m1", TypeName: "M1", Fields: []FieldDecl{{Name: "z", Type: "int64", Order: 1}}},
		},
	}
	sorted := &PackageDecl{
		Name: "x",
		Messages: []MessageDecl{
			{Name: "m1", TypeName: "M1", Fields: []FieldDecl{{Name: "z", Type: "int64", Order: 1}}},
			{Name: "m2", TypeName: "M2", Fields: []FieldDecl{{Name: "a", Type: "string", Order: 1}, {Name: "b", Type: "string", Order: 2}}},
		},
	}
	rs := renderPlan(t, shuffled)
	rk := renderPlan(t, sorted)
	if !bytes.Equal(rs, rk) {
		t.Fatalf("乱序/正序输入渲染不一致:\n%s\n---\n%s", rs, rk)
	}
	if !reflect.DeepEqual(shuffled, sorted) {
		t.Fatalf("planGen 未就地归一: %+v", shuffled)
	}
}

// TestPlanShapesPerField 形状清单规划（完整指纹形态）：每消息每字段
// 一条 "TypeName:Field:Order:Type"（Type 为源码形态类型串），整体字典序；
// 字段乱序输入经排序归一。
func TestPlanShapesPerField(t *testing.T) {
	msgs := []MessageDecl{
		{Name: "m.b", TypeName: "B", Fields: []FieldDecl{
			{Name: "z", Type: "int64", Order: 2},
			{Name: "a", Type: "string", Order: 1},
		}},
		{Name: "m.a", TypeName: "A", Fields: []FieldDecl{
			{Name: "k", Type: "[]string", Order: 1},
		}},
		{Name: "m.empty", TypeName: "Empty"}, // 零字段消息：仅类型名条目
	}
	got := planShapes(msgs)
	want := []string{
		"A:k:1:[]string",
		"B:a:1:string",
		"B:z:2:int64",
		"Empty", // 零字段消息的增删/改名同样翻指纹
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("planShapes = %v, want %v", got, want)
	}
}

// TestEntityDemoShapesDerivedRequests entity_demo 形状清单抽查（含方法派生
// 请求与用户手写请求）：字段名/序/型逐条对账。
func TestEntityDemoShapesDerivedRequests(t *testing.T) {
	pkg, err := LoadPackage(entityFixtureDir, "rans_gen.go")
	if err != nil {
		t.Fatalf("LoadPackage: %v", err)
	}
	model, err := planGen(pkg)
	if err != nil {
		t.Fatalf("planGen: %v", err)
	}
	want := []string{
		"CounterAddRequest:Delta:1:int64", // 派生（参数名 delta → Delta）
		"CounterBumpRequest:Arg1:1:int64", // 派生（未命名参数 → Arg1）
		"CounterPingRequest",              // 零字段派生请求（无参方法）：仅类型名条目
		"CounterPutRequest:To:1:int64",    // 派生（//rans:idempotent 不影响形状）
		"CounterResetRequest:Val:1:int64", // 用户手写请求
		"CounterResetRequest:Who:2:string",
	}
	if !reflect.DeepEqual(model.Shapes, want) {
		t.Fatalf("Shapes = %v, want %v", model.Shapes, want)
	}
}

